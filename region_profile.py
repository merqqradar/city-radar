def _override_paths():
    import os
    import sys
    from pathlib import Path

    paths = []
    data_dir = os.getenv("RADAR_DATA_DIR", "").strip()
    if data_dir:
        paths.append(Path(data_dir) / "region_profile.json")
    if getattr(sys, "frozen", False):
        paths.append(Path.home() / "Library" / "Application Support"
                     / "CityRadar" / "data" / "region_profile.json")
    paths.append(Path(__file__).resolve().parent / "data" / "region_profile.json")
    return paths


def _apply_overrides() -> None:
    import json
    import os

    global SOURCE
    raw, origin = os.getenv("RADAR_REGION_JSON", "").strip(), "RADAR_REGION_JSON"
    if not raw:
        for path in _override_paths():
            if path.exists():
                raw, origin = path.read_text(encoding="utf-8"), str(path)
                break
    if not raw:
        return
    try:
        data = json.loads(raw)
    except ValueError as exc:
        raise SystemExit(f"Профіль регіону ({origin}) — некоректний JSON: {exc}")
    g = globals()
    for key in ("OBLAST_LABEL", "OBLAST_ROOTS", "OBLAST_ALONE", "OBLAST",
                "HOME_COMMUNITY", "CIVIL_SKIP"):
        if key in data:
            g[key] = data[key]
    for key in ("CLOSE", "FAR"):
        if key in data:
            g[key] = {name: list(roots) for name, roots in data[key].items()}
    if "NEAR" in data:
        near = {}
        for name, val in data["NEAR"].items():
            if val and isinstance(val[0], (list, tuple)):
                near[name] = (list(val[0]), list(val[1]) if len(val) > 1 else [])
            else:
                near[name] = (list(val), [])
        g["NEAR"] = near
    SOURCE = f"JSON: {origin}"


_apply_overrides()
